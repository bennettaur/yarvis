import { describe, expect, it } from "bun:test";
import {
  extractText,
  parseHistory,
  parsePlanTitle,
  parseRecentActivity,
  parseSessionSummary,
  parseTranscript,
} from "./parse.ts";

const transcript = [
  JSON.stringify({ type: "custom-title", customTitle: "My Session", sessionId: "s1" }),
  JSON.stringify({
    type: "user",
    sessionId: "s1",
    timestamp: "2026-05-01T10:00:00Z",
    cwd: "/Users/x/proj",
    gitBranch: "main",
    message: { role: "user", content: "first prompt" },
  }),
  JSON.stringify({
    type: "assistant",
    sessionId: "s1",
    timestamp: "2026-05-01T10:01:00Z",
    message: {
      role: "assistant",
      content: [
        { type: "text", text: "hello" },
        { type: "tool_use", name: "Bash" },
      ],
    },
  }),
  JSON.stringify({ type: "last-prompt", lastPrompt: "final prompt", sessionId: "s1" }),
  "definitely not json{",
].join("\n");

describe("cc parsers", () => {
  it("summarizes a session, skipping malformed lines", () => {
    const s = parseSessionSummary(transcript);
    expect(s.id).toBe("s1");
    expect(s.title).toBe("My Session");
    expect(s.firstPrompt).toBe("first prompt");
    expect(s.lastPrompt).toBe("final prompt");
    expect(s.messageCount).toBe(2);
    expect(s.cwd).toBe("/Users/x/proj");
    expect(s.gitBranch).toBe("main");
    expect(s.startedAt).toBe("2026-05-01T10:00:00Z");
    expect(s.updatedAt).toBe("2026-05-01T10:01:00Z");
  });

  it("extracts text from string and block-array content", () => {
    expect(extractText("plain")).toBe("plain");
    expect(
      extractText([
        { type: "text", text: "a" },
        { type: "tool_use", name: "Edit" },
        { type: "tool_result" },
      ]),
    ).toBe("a\n[tool: Edit]\n[tool result]");
  });

  it("builds a transcript of user/assistant entries", () => {
    const entries = parseTranscript(transcript);
    expect(entries.length).toBe(2);
    expect(entries[0]).toMatchObject({ role: "user", text: "first prompt" });
    expect(entries[1]!.text).toBe("hello\n[tool: Bash]");
  });

  it("parses history newest-first with a limit", () => {
    const content = [
      JSON.stringify({ display: "older", project: "/a", timestamp: 1 }),
      JSON.stringify({ display: "newer", project: "/b", timestamp: 2 }),
    ].join("\n");
    const entries = parseHistory(content, 1);
    expect(entries.length).toBe(1);
    expect(entries[0]!.display).toBe("newer");
  });

  it("reads the first markdown H1 as the plan title", () => {
    expect(parsePlanTitle("intro\n# The Plan\nbody")).toBe("The Plan");
    expect(parsePlanTitle("no heading here")).toBeNull();
  });

  describe("parseRecentActivity", () => {
    const at = (minute: number) => `2026-05-01T10:${String(minute).padStart(2, "0")}:00Z`;
    const user = (minute: number, content: unknown, extra: Record<string, unknown> = {}) =>
      JSON.stringify({
        type: "user",
        timestamp: at(minute),
        message: { role: "user", content },
        ...extra,
      });
    const assistant = (minute: number, content: unknown, extra: Record<string, unknown> = {}) =>
      JSON.stringify({
        type: "assistant",
        timestamp: at(minute),
        message: { role: "assistant", content },
        ...extra,
      });

    it("keeps only what the user typed, newest last", () => {
      const content = [
        user(1, "add a login page"),
        assistant(2, [{ type: "tool_use", name: "Edit" }]),
        user(3, [{ type: "tool_result", content: "ok" }]),
        user(4, "<command-name>/clear</command-name>"),
        user(5, "<local-command-stdout>done</local-command-stdout>"),
        user(6, "Caveat: the messages below were generated by the user"),
        user(7, "[Request interrupted by user]"),
        user(8, "injected context", { isMeta: true }),
        user(9, "subagent task", { isSidechain: true }),
        user(10, "summary of earlier", { isCompactSummary: true }),
        user(11, [
          { type: "text", text: "<system-reminder>be careful</system-reminder>" },
          { type: "text", text: "now add a logout button" },
        ]),
      ].join("\n");
      const activity = parseRecentActivity(content, 5);
      expect(activity.prompts.map((p) => p.text)).toEqual([
        "add a login page",
        "now add a logout button",
      ]);
      expect(activity.prompts[1]!.timestamp).toBe(at(11));
    });

    it("strips a reminder embedded in a typed prompt", () => {
      const activity = parseRecentActivity(
        user(1, "fix the bug<system-reminder>hidden</system-reminder>"),
        5,
      );
      expect(activity.prompts.map((p) => p.text)).toEqual(["fix the bug"]);
    });

    it("limits to the newest prompts", () => {
      const content = [user(1, "one"), user(2, "two"), user(3, "three")].join("\n");
      expect(parseRecentActivity(content, 2).prompts.map((p) => p.text)).toEqual(["two", "three"]);
    });

    it("takes the agent's last text reply, skipping tool-only turns and subagents", () => {
      const content = [
        user(1, "ship it"),
        assistant(2, [{ type: "text", text: "Opened the PR." }]),
        assistant(3, [{ type: "tool_use", name: "Bash" }]),
        assistant(4, [{ type: "text", text: "subagent chatter" }], { isSidechain: true }),
      ].join("\n");
      const activity = parseRecentActivity(content, 5);
      expect(activity.lastReply).toEqual({ text: "Opened the PR.", timestamp: at(2) });
      // Activity includes the turns the reply skipped.
      expect(activity.lastActivityAt).toBe(at(4));
    });

    it("reports nothing for a session with no typed prompts", () => {
      const activity = parseRecentActivity(user(1, [{ type: "tool_result" }]), 5);
      expect(activity.prompts).toEqual([]);
      expect(activity.lastReply).toBeNull();
    });
  });
});
